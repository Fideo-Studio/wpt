import argparse
import json
import os
import posixpath
import sys
from typing import Any, Dict, List


here = os.path.dirname(__file__)
wpt_root = os.path.abspath(os.path.join(here, os.pardir, os.pardir))

TEST262_DIR = os.path.join("third_party", "test262")


def validate_manifest(manifest: Any, test262_root: str) -> List[str]:
    """
    Checks that a web-features manifest generated by Test262's tooling has the
    expected shape and only lists tests that exist in the vendored tree.

    Returns:
        List[str]: A list of error messages, empty if the manifest is valid.
    """
    if not isinstance(manifest, dict) or manifest.get("version") != 1:
        return ["Expected a manifest object with version 1"]
    data = manifest.get("data")
    if not isinstance(data, dict):
        return ["Expected data to map web-feature IDs to lists of test paths"]

    errors = []
    for feature_id, paths in data.items():
        if not isinstance(paths, list) or not all(isinstance(path, str) for path in paths):
            errors.append(f"Expected a list of test paths for {feature_id}")
            continue
        for path in paths:
            norm_path = os.path.normpath(path)
            if (norm_path.split(os.path.sep)[0] != "test" or
                    not os.path.isfile(os.path.join(test262_root, norm_path))):
                errors.append(f"{feature_id} lists a missing test: {path}")
    return errors


def normalize_manifest(manifest: Dict[str, Any]) -> Dict[str, Any]:
    """
    Returns a copy of a valid manifest with normalized, deduplicated and sorted
    test paths, so that regenerating an unchanged mapping produces no diff.
    """
    return {
        "version": manifest["version"],
        "data": {feature_id: sorted({posixpath.normpath(path) for path in paths})
                 for feature_id, paths in manifest["data"].items()},
    }


def get_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Validate a web-features manifest generated by Test262's tooling "
                    "against the vendored tests, and rewrite it in a stable form.")
    parser.add_argument("path", help="Path to the generated manifest")
    return parser


def main() -> int:
    args = get_parser().parse_args()
    with open(args.path) as f:
        manifest = json.load(f)

    errors = validate_manifest(manifest, os.path.join(wpt_root, TEST262_DIR))
    for error in errors:
        print(error, file=sys.stderr)
    if errors:
        return 1

    with open(args.path, "w") as f:
        json.dump(normalize_manifest(manifest), f, indent=2, sort_keys=True)
        f.write("\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
